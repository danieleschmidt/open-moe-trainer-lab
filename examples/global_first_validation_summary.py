    print(f"   Validation Score: {results.get('validation_score', 'N/A')}/100")
    
    # Print key capabilities
    if 'capabilities' in results:
        capabilities = results['capabilities']
        enabled_count = sum(1 for v in capabilities.values() if v)
        total_count = len(capabilities)
        print(f"   Capabilities: {enabled_count}/{total_count} enabled")
    
    # Print supported features count
    for key in ['supported_regions', 'supported_locales', 'frameworks_supported']:
        if key in results:
            feature_name = key.replace('_', ' ').title()
            print(f"   {feature_name}: {results[key]}")


